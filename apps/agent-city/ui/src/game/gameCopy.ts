export function gameText(text: string, locale: GameLocale): string {
  if (locale !== "en") return text;
  const translated = ENGLISH[text];
  // Keep dynamic error/reason text inspectable when a new source phrase has no
  // translation yet; make the missing translation explicit without dropping it.
  return translated ?? (/\p{Script=Han}/u.test(text) ? `Translation unavailable: ${text}` : text);
}
