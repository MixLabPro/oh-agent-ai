export type MessageKey = keyof typeof english;

function validPreference(value: unknown): value is LanguagePreference {
  return value === "system" || value === "en" || value === "zh-Hans";
}

function applyLanguagePreference(preference: LanguagePreference): void {
  try { localStorage.setItem(languageStorageKey, preference); } catch { /* preference is optional */ }
  window.dispatchEvent(new Event(eventName));
}

export async function hydrateLanguagePreference(): Promise<void> {
  if (!hasNativeBridge()) return;
  const result = await invoke<{ status: string; language: unknown; has_preference: unknown }>("ui_language_config");
  if (result.status !== "ok" || !validPreference(result.language) || typeof result.has_preference !== "boolean") throw new Error("UI language preference unavailable");
  const local = languagePreference();
  if (!result.has_preference && local !== "system") {
    await invoke("save_ui_language_config", { language: local });
    return;
  }
  applyLanguagePreference(result.language);
}

export async function setLanguagePreference(preference: LanguagePreference): Promise<void> {
  if (!validPreference(preference)) throw new Error("Unsupported UI language preference");
  if (hasNativeBridge()) {
    const result = await invoke<{ status: string; language: unknown }>("save_ui_language_config", { language: preference });
    if (result.status !== "saved" || result.language !== preference) throw new Error("UI language preference was not saved");
  }
  applyLanguagePreference(preference);
}

export function message(key: MessageKey, language = resolvedLanguage(), parameters: Record<string, string | number> = {}): string {
  const value: Translation = (language === "en" ? english[key] : chinese[key]) ?? english[key] ?? "Unavailable";
  const template = typeof value === "string" ? value : new Intl.PluralRules(language === "en" ? "en-US" : "zh-CN").select(Number(parameters.count)) === "one" ? value.one : value.other;
  return template.replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g, (_, name: string) => String(parameters[name] ?? `{${name}}`));
}

/** Called by the contract test so missing keys or mismatched interpolation cannot reach the release UI. */
export function translationIntegrityIssues(): string[] {
  const issues: string[] = [];
  const placeholders = (value: Translation): string[] => {
    const variants = typeof value === "string" ? [value] : [value.one, value.other];
    return [...new Set(variants.flatMap((variant) => [...variant.matchAll(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g)].map((match) => match[1])))].sort();
  };
  for (const key of Object.keys(english) as MessageKey[]) {
    const translated = chinese[key];
    if (translated === undefined) { issues.push(`missing zh-Hans: ${key}`); continue; }
    if (placeholders(english[key]).join(",") !== placeholders(translated).join(",")) issues.push(`placeholder mismatch: ${key}`);
  }
  for (const key of Object.keys(chinese)) if (!(key in english)) issues.push(`unknown zh-Hans key: ${key}`);
  return issues;
}

export function useLanguage(): AppLanguage {
  useSyncExternalStore((notify) => {
    window.addEventListener(eventName, notify);
    window.addEventListener("storage", notify);
    return () => { window.removeEventListener(eventName, notify); window.removeEventListener("storage", notify); };
  }, languagePreference, () => "system");
  return resolvedLanguage();
}

export function currencyLabel(currency: string): string {
  return /^[A-Z]{3}$/.test(currency) ? currency : "";
}

/** For known minor-unit amounts only. Never converts a source currency. */
export function formatMinorMoney(amountMinor: number | null, currency: string, locale = typeof navigator === "undefined" ? "en-US" : navigator.language): string {
  if (amountMinor === null || !Number.isSafeInteger(amountMinor) || !["USD", "CNY"].includes(currency)) return "—";
  const amount = amountMinor / 100;
  if (amountMinor !== 0 && Math.abs(amount) < 0.01) return `< ${currency} 0.01`;
  return new Intl.NumberFormat(locale, { style: "currency", currency, currencyDisplay: "code", minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(amount);
}

/** Display-only formatting for an already-denominated major-unit amount. Never sums currencies. */
export function formatMajorMoney(amount: number | null, currency: string, locale = typeof navigator === "undefined" ? "en-US" : navigator.language): string {
  if (amount === null || !Number.isFinite(amount) || !currencyLabel(currency)) return "—";
  if (!["USD", "CNY"].includes(currency)) return `${currency} ${amount}`;
  if (amount !== 0 && Math.abs(amount) < 0.01) return `< ${currency} 0.01`;
  return new Intl.NumberFormat(locale, { style: "currency", currency, currencyDisplay: "code", minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(amount);
}

export function formatNumber(value: number | null, locale = typeof navigator === "undefined" ? "en-US" : navigator.language): string {
  return value === null || !Number.isFinite(value) ? "—" : new Intl.NumberFormat(locale).format(value);
}

export function formatTokens(value: number | null, locale = typeof navigator === "undefined" ? "en-US" : navigator.language): string {
  if (value === null || !Number.isSafeInteger(value) || value < 0) return "—";
  return new Intl.NumberFormat(locale, { notation: "compact", maximumFractionDigits: 1 }).format(value);
}
