function fmt(s: string, params?: Record<string, string | number>): string {
  if (!params) return s
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in params ? String(params[k]) : '{' + k + '}'))
}

export function t(lang: Lang, key: string, params?: Record<string, string | number>): string {
  const s = STRINGS[lang][key] ?? STRINGS['zh-CN'][key] ?? key
  return fmt(s, params)
}

export function ruleLabel(lang: Lang, rule: string): string {
  const key = 'rule_' + rule
  return STRINGS[lang][key] ?? STRINGS['zh-CN'][key] ?? rule
}

export function severityLabel(lang: Lang, sev: string): string {
  const key = 'severity_' + sev
  return STRINGS[lang][key] ?? STRINGS['zh-CN'][key] ?? sev
}

// DSH 宿主的语言设置（如果提供了的话），优先级最高。
// 在 index.cts apply() 里通过 setHostLang() 注入。
let hostLang: Lang | undefined = undefined

export function setHostLang(lang: Lang | undefined) {
  hostLang = lang
}

function detectDefaultLang(): Lang {
  try {
    if (typeof navigator !== 'undefined' && typeof navigator.language === 'string') {
      return navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en'
    }
  } catch {
    // ignore — fall through to the zh-CN default
  }
  return 'zh-CN'
}

export function loadLang(): Lang {
  // 优先级：DSH 宿主语言 > navigator.language > zh-CN 默认
  if (hostLang) return hostLang
  return detectDefaultLang()
}

// Test helper: reset cached host lang (for verify.mjs).
export function resetLang() {
  hostLang = undefined
}
